# The assistant's own wording when the knowledge base didn't have the answer.
_UNANSWERED_RE = re.compile(
    r"team (?:will|can|would be happy to|is happy to) confirm|(?:i'?m|i am) not sure|"
    r"don'?t have (?:that|this|those|the) (?:information|details|info)|can'?t confirm|"
    r"isn'?t (?:something|in) (?:i have|my|the)|"
    r"(?:el|nuestro) equipo (?:le )?(?:puede|podr[aá]) confirmar|no estoy segur|no tengo (?:esa|esta|la) informaci[oó]n",
    re.I)

_EMAIL_RE = re.compile(r"[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}")
_PHONE_RE = re.compile(r"(?:\+?1[\s.\-]?)?\(?\d{3}\)?[\s.\-]?\d{3}[\s.\-]?\d{4}")
_DAY_NAMES = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]


def _mask(text: str) -> str:
    """Examples shown to the owner never repeat a prospect's contact details."""
    t = _PHONE_RE.sub("[phone]", _EMAIL_RE.sub("[email]", text or ""))
    t = " ".join(t.split())
    return t if len(t) <= 160 else t[:157].rstrip() + "..."


def _aware(dt):
    return dt if dt is None or dt.tzinfo else dt.replace(tzinfo=timezone.utc)


def _topics(text, catalog):
    return [(k, label) for k, label, rx in catalog if rx.search(text or "")]


def _topic_table(messages, catalog):
    """messages: [(text, when)] newest first -> [{key, label, count, examples}]"""
    counts, examples, labels = Counter(), defaultdict(list), {}
    for text, _ in messages:
        for key, label in _topics(text, catalog):
            counts[key] += 1
            labels[key] = label
            if len(examples[key]) < EXAMPLES_PER_TOPIC:
                examples[key].append(_mask(text))
    order = {k: i for i, (k, _, _) in enumerate(catalog)}
    rows = sorted(counts, key=lambda k: (-counts[k], order[k]))
    return [{"key": k, "label": labels[k], "count": counts[k], "examples": examples[k]} for k in rows]


def _pct(n, d):
    return round(100 * n / d) if d else 0


def build_insights(client_id: str, config: dict, days: int = 30, now: datetime | None = None) -> dict:
    days = days if days in ALLOWED_DAYS else 30
    now = now or datetime.now(timezone.utc)
    since = now - timedelta(days=days)
    sched = (config or {}).get("schedule") or {}
    try:
        tz = ZoneInfo(sched.get("timezone") or "America/New_York")
    except Exception:
        tz = ZoneInfo("America/New_York")

    db = SessionLocal()
    try:
        # ── Chats in the period, split into prospect and resident chats ──
        convs = (db.query(Conversation.session_id, Conversation.intents)
                 .filter(Conversation.client_id == client_id, Conversation.started_at >= since).all())
        resident_sids = {s for s, intents in convs if "resident" in (intents or [])}
        prospect_sids = {s for s, _ in convs} - resident_sids

        rows = []
        if convs:
            rows = (db.query(Message.session_id, Message.role, Message.content, Message.timestamp, Message.id)
                    .join(Conversation, Conversation.session_id == Message.session_id)
                    .filter(Conversation.client_id == client_id, Conversation.started_at >= since)
                    .order_by(Message.id.desc())
                    .limit(MAX_MESSAGES * 2).all())

        # ── Leads in the period ──
        leads = (db.query(Lead.status, Lead.pending_key, Lead.answers, Lead.flags, Lead.created_at,
                          Lead.contact_phone, Lead.contact_email)
                 .filter(Lead.client_id == client_id, Lead.created_at >= since).all())
        tours = (db.query(Appointment.property, Appointment.status, Appointment.start_at)
                 .filter(Appointment.client_id == client_id, Appointment.created_at >= since).all())
    finally:
        db.close()

    # Pair each visitor message with the assistant's reply to it.
    rows = list(reversed(rows))  # oldest first
    prospect_msgs, resident_msgs, unanswered = [], [], []
    for i, (sid, role, content, ts, _) in enumerate(rows):
        if role != "user":
            continue
        reply = rows[i + 1] if i + 1 < len(rows) and rows[i + 1][0] == sid and rows[i + 1][1] == "assistant" else None
        if sid in resident_sids:
            resident_msgs.append((content, ts))
        else:
            prospect_msgs.append((content, ts))
            if reply and _UNANSWERED_RE.search(reply[2] or ""):
                unanswered.append((content, ts))
    newest_first = lambda xs: list(reversed(xs))[:MAX_MESSAGES]
    prospect_topics = _topic_table(newest_first(prospect_msgs), PROSPECT_TOPICS)
    unanswered_topics = _topic_table(newest_first(unanswered), PROSPECT_TOPICS)
    unanswered_other = [_mask(t) for t, _ in newest_first(unanswered) if not _topics(t, PROSPECT_TOPICS)][:3]
    resident_topics = _topic_table(newest_first(resident_msgs), RESIDENT_TOPICS)

    # ── Funnel and drop-off ──
    real_leads = [l for l in leads if (l.answers or l.flags)]
    with_contact = [l for l in real_leads if l.contact_phone or l.contact_email]
    finished = [l for l in real_leads if l.status == "complete"]
    unfinished = [l for l in real_leads if l.status != "complete"]
    booked = [t for t in tours]
    canceled = [t for t in tours if t.status == "canceled"]
    stops = Counter(l.pending_key for l in unfinished if l.pending_key in QUESTION_CATALOG)
    drop_off = [{"key": k, "label": QUESTION_CATALOG[k]["label"], "count": n, "share": _pct(n, len(unfinished))}
                for k, n in stops.most_common()]

    # ── Properties ──
    by_prop = defaultdict(lambda: {"leads": 0, "finished": 0, "tours": 0})
    for l in real_leads:
        p = str((l.answers or {}).get("property") or "").strip()
        if p and p not in ("Not provided", "Prefers not to say"):
            by_prop[p]["leads"] += 1
            by_prop[p]["finished"] += l.status == "complete"
    for t in tours:
        if t.property and t.status != "canceled":
            by_prop[t.property]["tours"] += 1
    properties = sorted(({"name": k, **v} for k, v in by_prop.items()), key=lambda r: (-r["leads"], r["name"]))[:20]

    # ── When leads come in (owner's time zone) ──
    by_day, by_hour = Counter(), Counter()
    for l in real_leads:
        local = _aware(l.created_at).astimezone(tz)
        by_day[local.weekday()] += 1
        by_hour[local.hour] += 1
    after_hours = sum(1 for l in real_leads if (l.flags or {}).get("after_hours"))
    spanish = sum(1 for l in real_leads if (l.flags or {}).get("lang") == "es")
    busiest_day = max(by_day, key=lambda d: by_day[d]) if by_day else None
    busiest_hour = max(by_hour, key=lambda h: by_hour[h]) if by_hour else None

    funnel = [
        {"key": "chats", "label": "Chats (not counting residents)", "count": len(prospect_sids)},
        {"key": "leads", "label": "Started the questions", "count": len(real_leads)},
        {"key": "contact", "label": "Shared a phone or email", "count": len(with_contact)},
        {"key": "finished", "label": "Answered every question", "count": len(finished)},
        {"key": "tours", "label": "Booked a tour", "count": len(booked)},
    ]

    suggestions = _suggestions(days, config or {}, unanswered_topics, unfinished, drop_off, finished,
                               real_leads, after_hours, spanish, resident_sids, resident_topics)

    return {
        "days": days,
        "metrics": leasing_metrics(client_id, days),
        "funnel": funnel,
        "tours_canceled": len(canceled),
        "drop_off": drop_off,
        "unanswered": {"total": len(unanswered), "topics": unanswered_topics, "other_examples": unanswered_other},
        "prospect_topics": prospect_topics,
        "resident": {"chats": len(resident_sids), "messages": len(resident_msgs), "topics": resident_topics},
        "properties": properties,
        "timing": {
            "by_day": [{"day": _DAY_NAMES[d], "count": by_day.get(d, 0)} for d in range(7)],
            "busiest_day": _DAY_NAMES[busiest_day] if busiest_day is not None else None,
            "busiest_hour": busiest_hour,
            "after_hours": after_hours, "after_hours_share": _pct(after_hours, len(real_leads)),
            "spanish": spanish, "spanish_share": _pct(spanish, len(real_leads)),
        },
        "suggestions": suggestions,
    }


def _suggestions(days, config, unanswered_topics, unfinished, drop_off, finished, real_leads,
                 after_hours, spanish, resident_sids, resident_topics) -> list[dict]:
    """Fixed rules over the counts above. Each fires only past its minimum
    sample, states the numbers it used ("basis"), and never guesses a cause."""
    out = []
    period = f"the last {days} days"

    for t in unanswered_topics:
        if t["count"] >= MIN_UNANSWERED:
            out.append({
                "kind": "knowledge_gap", "priority": 1,
                "title": f"Add a knowledge base article about {t['label'].lower()}",
                "detail": (f"{t['count']} prospect questions about {t['label'].lower()} in {period} got "
                           "\"our team will confirm\" because your knowledge base didn't have the answer. "
                           "Adding it lets the assistant answer right away."),
                "basis": f"{t['count']} unanswered questions on this topic",
                "examples": t["examples"],
            })

    if len(unfinished) >= MIN_UNFINISHED and drop_off:
        top = drop_off[0]
        if top["share"] >= 30:
            required = top["key"] == "name" or top["key"] in CONTACT_KEYS
            out.append({
                "kind": "drop_off", "priority": 2,
                "title": f"Most prospects who stop, stop at \"{top['label']}\"",
                "detail": (f"{top['count']} of the {len(unfinished)} prospects who didn't finish in {period} "
                           f"stopped at the {top['label'].lower()} question."
                           + ("" if required else " If you don't need that answer, turning the question off "
                              "under Leasing assistant may help more people finish.")),
                "basis": f"{top['count']} of {len(unfinished)} unfinished intakes",
                "examples": [],
            })

    sched_on = bool((config.get("schedule") or {}).get("enabled"))
    asked_time = [l for l in finished if str((l.answers or {}).get("tour_time") or "").strip()
                  and not str(l.answers["tour_time"]).startswith(("Booked", "Not ", "No ", "Didn't", "Canceled"))]
    if not sched_on and len(asked_time) >= MIN_LEADS:
        out.append({
            "kind": "booking", "priority": 2,
            "title": "Turn on online booking",
            "detail": (f"{len(asked_time)} prospects in {period} told the assistant when they'd like a tour "
                       "and then had to wait for a call back. With online booking on, they can pick a real "
                       "open time in the chat."),
            "basis": f"{len(asked_time)} finished leads with a preferred tour time",
            "examples": [],
        })

    if len(real_leads) >= MIN_LEADS and _pct(after_hours, len(real_leads)) >= 30:
        out.append({
            "kind": "after_hours", "priority": 3,
            "title": f"{_pct(after_hours, len(real_leads))}% of your leads came in after hours",
            "detail": (f"{after_hours} of {len(real_leads)} leads in {period} arrived outside your weekly "
                       "hours. They're tagged After hours in Leads, so you can call them first thing."),
            "basis": f"{after_hours} of {len(real_leads)} leads",
            "examples": [],
        })

    if len(real_leads) >= MIN_LEADS and spanish >= 2 and _pct(spanish, len(real_leads)) >= 10:
        out.append({
            "kind": "spanish", "priority": 3,
            "title": f"{_pct(spanish, len(real_leads))}% of prospects chatted in Spanish",
            "detail": (f"{spanish} of {len(real_leads)} leads in {period} chatted in Spanish. If your listings "
                       "or application are English only, a Spanish version may help them take the next step."),
            "basis": f"{spanish} of {len(real_leads)} leads",
            "examples": [],
        })

    if len(resident_sids) >= MIN_RESIDENT and not (config.get("resident_contact") or "").strip():
        out.append({
            "kind": "resident_contact", "priority": 1,
            "title": "Add a contact for current residents",
            "detail": (f"{len(resident_sids)} current residents asked for help in {period}, but no resident "
                       "contact is set, so the assistant couldn't point them to your office. Add one under "
                       "Leasing assistant."),
            "basis": f"{len(resident_sids)} resident chats",
            "examples": [],
        })

    if resident_topics and resident_topics[0]["count"] >= MIN_RESIDENT:
        t = resident_topics[0]
        out.append({
            "kind": "resident_trend", "priority": 2,
            "title": f"Residents' top issue: {t['label'].lower()}",
            "detail": (f"Residents brought up {t['label'].lower()} {t['count']} times in {period}, more than "
                       "any other topic. The examples below are their own words."),
            "basis": f"{t['count']} resident messages on this topic",
            "examples": t["examples"],
        })

    return sorted(out, key=lambda s: s["priority"])
