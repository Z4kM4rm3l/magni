MAX_MESSAGES = 5000      # newest user messages examined per report
EXAMPLES_PER_TOPIC = 2

# Minimum sample sizes before a suggestion is shown.
MIN_UNANSWERED = 3
MIN_UNFINISHED = 5
MIN_LEADS = 5
MIN_RESIDENT = 3


