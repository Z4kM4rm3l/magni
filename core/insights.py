"""
core/insights.py

What an owner's own data says about filling units and keeping residents happy.

Nothing here is generated by a model and nothing is guessed. Every number is
counted from the tenant's own chats, leads and appointments, and every
suggestion is a fixed rule that only fires when its numbers clear a minimum
sample size. Each suggestion carries the numbers it is based on, and each
topic carries real (masked) examples, so the owner can check it.

Topics are found by fixed keyword lists in English and Spanish. A message can
match more than one topic or none; nothing is forced into a bucket. Topics
describe the PROPERTY or the request, never the people asking (Fair Housing):
there is deliberately no topic for schools, "safe areas", families, etc.
"""
